import { randomBytes } from 'node:crypto';

/** Accepted uploads, keyed by the MIME type detected from the file's content (never its name). */
export const ACCEPTED_MEDIA = {
  'image/jpeg': { ext: 'jpg', kind: 'image', raster: true },
  'image/png': { ext: 'png', kind: 'image', raster: true },
  'image/webp': { ext: 'webp', kind: 'image', raster: true },
  'image/avif': { ext: 'avif', kind: 'image', raster: true },
  'image/gif': { ext: 'gif', kind: 'image', raster: false },
  'application/pdf': { ext: 'pdf', kind: 'document', raster: false },
  'video/mp4': { ext: 'mp4', kind: 'video', raster: false },
  'video/webm': { ext: 'webm', kind: 'video', raster: false },
  'audio/mpeg': { ext: 'mp3', kind: 'audio', raster: false },
  'audio/ogg': { ext: 'ogg', kind: 'audio', raster: false },
  'audio/wav': { ext: 'wav', kind: 'audio', raster: false },
} as const satisfies Record<string, { ext: string; kind: MediaKind; raster: boolean }>;

export type MediaKind = 'image' | 'video' | 'audio' | 'document';
export type AcceptedMime = keyof typeof ACCEPTED_MEDIA;

export function isAcceptedMime(mime: string): mime is AcceptedMime {
  return Object.hasOwn(ACCEPTED_MEDIA, mime);
}

export function kindOf(mime: string): MediaKind {
  return isAcceptedMime(mime) ? ACCEPTED_MEDIA[mime].kind : 'document';
}

const CONTENT_TYPE_BY_EXT: Readonly<Record<string, string>> = Object.fromEntries(
  Object.entries(ACCEPTED_MEDIA).map(([mime, info]) => [info.ext, mime]),
);

/**
 * Storage keys are generated by the server: `YYYY/MM/<random>/<ascii-name>[-<width>w].<ext>`. Serving
 * only accepts keys matching this pattern, which rules out traversal and unexpected file types.
 */
export const STORAGE_KEY_PATTERN =
  /^\d{4}\/\d{2}\/[A-Za-z0-9_-]{12}\/[a-z0-9](?:[a-z0-9-]{0,79})\.(?:jpg|png|webp|avif|gif|pdf|mp4|webm|mp3|ogg|wav)$/;

export function isValidStorageKey(key: string): boolean {
  return STORAGE_KEY_PATTERN.test(key);
}

export function contentTypeForKey(key: string): string | null {
  const ext = key.slice(key.lastIndexOf('.') + 1);
  return CONTENT_TYPE_BY_EXT[ext] ?? null;
}

/** ASCII file-name stem for URLs: accents removed, everything else collapsed to hyphens. */
export function safeBaseName(filename: string): string {
  const stem = filename.replace(/\.[^.]*$/, '');
  const ascii = stem
    .normalize('NFKD')
    .replace(/\p{M}+/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
    .replace(/-+$/, '');
  return ascii === '' ? 'file' : ascii;
}

export function newStorageKey(filename: string, ext: string, now = new Date()): string {
  const year = String(now.getUTCFullYear());
  const month = String(now.getUTCMonth() + 1).padStart(2, '0');
  const token = randomBytes(9).toString('base64url');
  return `${year}/${month}/${token}/${safeBaseName(filename)}.${ext}`;
}

/** Key of a resized variant, next to the original: `.../<name>-<width>w.webp`. */
export function variantKey(originalKey: string, width: number): string {
  return originalKey.replace(/\.[a-z0-9]+$/, `-${String(width)}w.webp`);
}

/** Display name of an upload: path components and control characters removed, length bounded. */
export function displayFilename(original: string): string {
  // eslint-disable-next-line no-control-regex -- stripping control characters on purpose
  const name = (original.split(/[\\/]/).pop() ?? '').replace(/[\u0000-\u001f\u007f]/g, '').trim();
  return (name === '' ? 'file' : name).slice(0, 255);
}
